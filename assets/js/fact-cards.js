function fcStartTimer(){
  FC.started=true; FC.startT=Date.now();
  FC.timer=setInterval(fcTick,200); fcTick();
}
function fcTick(){
  if(FC.screen!=="game") return;
  var el=(Date.now()-FC.startT)/1000;
  if(FC.durMin>0){
    var left=FC.durMin*60-el;
    fcEl("fcTime").textContent=fmtTime(Math.max(0,left));
    if(left<=0) fcFinish();
  } else {
    fcEl("fcTime").textContent=fcClock(el);
  }
}
function fcCompleteCard(){
  FC.busy=true;
  var perfect= FC.typed===FC.fact, correct=0, i;
  for(i=0;i<FC.fact.length;i++){ if(FC.typed[i]===FC.fact[i]) correct++; }
  FC.totalChars+=FC.fact.length; FC.correctChars+=correct; FC.done++;
  if(perfect){ FC.perfect++; FC.streak++; if(FC.streak>FC.best) FC.best=FC.streak; }
  else { FC.missed++; FC.streak=0; }
  fcHud();
  var card=fcEl("fcCard");
  FC_ANIMS.forEach(function(a){ card.classList.remove(a); });
  card.classList.add(perfect?"fcGood":"fcBad");
  fcEl("fcVerdict").textContent= perfect? "✓ Perfect!" : "✗ One mistake!";
  if(perfect&&FC.streak>=3){
    var b=fcEl("fcBurst"); b.textContent="🔥 Streak ×"+FC.streak; b.classList.add("on");
    setTimeout(function(){ b.classList.remove("on"); },1000);
  }
  var sid=FC.session, wasPerfect=perfect, cat=FC.cat, fact=FC.fact;
  setTimeout(function(){
    if(sid!==FC.session||FC.screen!=="game") return;
    card.classList.add(wasPerfect?"fcExitL":"fcExitR");
    fcPushMini(wasPerfect,cat,fact);
    setTimeout(function(){
      if(sid!==FC.session||FC.screen!=="game") return;
      fcNextCard();
    },400);
  },780);
}
