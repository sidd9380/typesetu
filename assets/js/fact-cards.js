function fcBuildSpans(){
  var tt=fcEl("fcTypeText"); tt.innerHTML="";
  for(var i=0;i<FC.fact.length;i++){ var s=document.createElement("span"); s.className="ch"; s.textContent=FC.fact[i]; tt.appendChild(s); }
  fcEl("fcCapture").value="";
}
function fcRender(){
  var tt=fcEl("fcTypeText"), pos=FC.typed.length, kids=tt.children;
  for(var i=0;i<kids.length;i++){
    var glyph= i<pos? FC.typed[i] : FC.fact[i];
    if(kids[i].textContent!==glyph) kids[i].textContent=glyph;
    var cls= i<pos? "ch typed" : (i===pos? "ch cur" : "ch");
    if(kids[i].className!==cls) kids[i].className=cls;
  }
  fcPositionCaret(pos);
}
function fcOffsetInBox(node){
  var x=0,y=0,n=node,box=fcEl("fcTypeBox");
  while(n&&n!==box){ x+=(n.offsetLeft||0); y+=(n.offsetTop||0); n=n.offsetParent; }
  return {x:x,y:y};
}
function fcPositionCaret(pos){
  var el=fcEl("fcCaret"); if(!el) return;
  var tt=fcEl("fcTypeText"), kids=tt.children, total=kids.length;
  if(!total){ el.classList.remove("on"); return; }
  var lh=parseFloat(window.getComputedStyle(tt).lineHeight); if(isNaN(lh)||lh<=0) lh=42;
  var x,y,idx=Math.min(pos,total-1), span=kids[idx];
  if(pos<total){
    var off=fcOffsetInBox(span);
    if((span.offsetWidth===0||span.offsetHeight===0)&&pos>0){ var p=kids[pos-1], po=fcOffsetInBox(p); x=po.x+(p.offsetWidth||0); y=po.y; }
    else { x=off.x; y=off.y; }
  } else {
    var lo=fcOffsetInBox(span); x=lo.x+(span.offsetWidth||0); y=lo.y;
  }
  el.style.left=(x-1)+"px"; el.style.top=(y+lh*0.14)+"px"; el.style.height=(lh*0.72)+"px";
  el.classList.add("on");

  var box=fcEl("fcTypeBox"), lineTop=y, lineBottom=y+lh;
  var viewTop=box.scrollTop, viewBottom=viewTop+box.clientHeight;
  var desired=box.scrollTop;
  if(lineBottom+lh>viewBottom) desired=lineBottom+lh-box.clientHeight;
  if(lineTop-lh<desired) desired=lineTop-lh;
  var maxScroll=Math.max(0,box.scrollHeight-box.clientHeight);
  if(desired>maxScroll) desired=maxScroll; if(desired<0) desired=0;
  if(desired!==box.scrollTop) box.scrollTop=desired;
}
